PROMPT_VARIANTS: dict[str, str] = {
    "standard": SYSTEM_PROMPT_STANDARD,
    "expert": SYSTEM_PROMPT_EXPERT,
    "warm": SYSTEM_PROMPT_WARM,
}


def build_system_prompt(
    *,
    anonymized_context: str,
    knowledge_base: str,
    variant: str = "standard",
) -> str:
    """Собрать system-prompt с выбранным A/B-вариантом.

    ВАЖНО: crm_context не принимается в принципе — только анонимизированный
    блок, чтобы исключить утечку ПД в LLM (152-ФЗ).
    """
    template = PROMPT_VARIANTS.get(variant.lower(), SYSTEM_PROMPT_STANDARD)
    return template.format(
        knowledge_base=knowledge_base,
        anonymized_context=anonymized_context,
    )


def list_variants() -> list[str]:
    """Доступные варианты промптов (для UI-селектора)."""
    return list(PROMPT_VARIANTS.keys())